#!/usr/bin/env python3
# -*- coding: utf-8 -*-
"""
Global configuration of the TV Control agent.
All the constants used by the other modules are here, so they are
not duplicated or scattered across the code.
"""

from pathlib import Path

# --- Language of the Raspberry: "fr", "en" or "es" ---
# Used for the voice announcement, the messages of the agent and of the
# setup scripts, and for the TV screen (passed to receveur.html by
# launch_chromium.sh).
LANGUAGE = "fr"

# --- How the voice announcement greets the person called ---
# e.g. "mamie", "papi", "maman", "papa" or a first name: "Hé mamie, c'est Paul
# qui t'appelle". None = without greeting: "C'est Paul qui t'appelle".
# Asked by install.sh at the first installation (option --greeting).
GREETING_NAME = None

# --- Name of this TV for the other TVs (settings page of the TV) ---
# How the other TVs show this one in their contacts and call it by voice
# ("Mamie": "Robot, appelle Mamie"), and the name announced when this TV
# calls. None = the name of its first owner (app), else its identifier.
TV_NAME = None

# --- Place of the weather of the home screen (TV page) ---
# Town, postal code and country of the Raspberry, e.g. "Clermont-Ferrand",
# "63000", "France" (or "FR"). Asked by install.sh at the first installation
# (options --city, --postcode, --country); each one may be None. Without a
# town nor a postal code: no weather on the TV. Only the place is sent to the
# weather service (Open-Meteo, through the server), never the identity of the
# Raspberry. Restart the agent (or the Raspberry) after a change.
WEATHER_CITY = None
WEATHER_POSTCODE = None
WEATHER_COUNTRY = None

# --- Server connection ---
SERVER_URL = "wss://appelermami.fr"

# --- Delay (in seconds) between two attempts when the server refuses the
#     device (device not yet authorized by the server administrator) ---
UNAUTHORIZED_RETRY_DELAY = 30

# --- Installation folder on the Raspberry (~/AppelerMamie) ---
BASE_DIR = Path.home() / "AppelerMamie"

# --- Identity file of the Raspberry (generated by setup_identity.py) ---
IDENTITY_FILE = BASE_DIR / "identity.json"

# --- Cache folder for the audio files generated by the TTS ---
CACHE_DIR = BASE_DIR / "cache_audio"
CACHE_DIR.mkdir(parents=True, exist_ok=True)

# --- Mouse used as the button that accepts a call ---
# None = automatic detection: the first device with a left button is used,
# whatever its model or USB port, and it is found again after being
# unplugged and plugged back in.
# To force a specific device, give its path, preferably the stable one from
# /dev/input/by-id/ (e.g. "/dev/input/by-id/usb-Logitech_USB_Optical_Mouse-event-mouse").
MOUSE_DEVICE = None

# --- Delay (in seconds) between two searches for the mouse when it is missing ---
MOUSE_RETRY_DELAY = 5

# --- HDMI input of the TV the Raspberry is plugged into (1, 2, 3, 4...) ---
# Used only if the TV does not give it: the input is normally read from the
# TV itself (physical address "3.0.0.0" = input 3, see `cec-ctl -d /dev/cec0`).
HDMI_PORT = 3

# --- Sound card used for the ringtone and the voice announcement ---
# None = automatic detection: the first USB sound card that can play sound
# is used (the microphone of a USB webcam is skipped),
# whatever its model or USB port (searched again at every call, so a speaker
# unplugged and plugged back in is found again). Without a USB speaker, the
# ringtone is played on the default output of the system (HDMI = the TV,
# only heard if the TV is on).
# To force a specific card, give its ALSA name as shown by `aplay -l`
# (the word between brackets in /proc/asound/cards), e.g. "AUDIO".
# NB: the sound of the call itself is chosen by CALL_AUDIO_OUTPUT below.
AUDIO_DEVICE = None

# --- Output of the call sound (the voice of the caller, call_audio.py) ---
# "auto" = on the TV (HDMI) when a TV answers HDMI-CEC and accepts sound,
# otherwise on the USB speaker above (computer monitor without sound, TV
# without CEC). Chosen again at every call, after the TV is turned on.
# "hdmi" or "usb" = always this output.
CALL_AUDIO_OUTPUT = "auto"

# --- Robot of the home screen that reacts to sounds (sound_level.py) ---
# True = outside calls, the volume of the microphone is measured (nothing is
# recorded or sent): the robot of the TV page moves when someone speaks.
# False = microphone never used outside calls.
VOICE_REACTION = True

# --- Spoken commands to the robot (voice_commands.py) ---
# True = "Robot bonjour" (or "Bonjour robot") makes the robot wave on the TV
# and answer on the speaker; also "Robot, quelle heure est-il ?", "quel temps
# fait-il ?", "mets la radio", "radio 101.2", "stop", "volume 5", "appelle
# <TV contact>". Recognized on the Raspberry itself (Vosk model installed by
# install.sh), never during a call; needs VOICE_REACTION = True (same
# microphone). False = no spoken commands.
VOICE_COMMANDS = True

# --- Radio (radio.py, radio page of the TV) ---
# None = the stations of the country of the TV (radio_stations.py: France,
# Spain, United Kingdom, Portugal, Mexico, United States), chosen from
# WEATHER_COUNTRY (settings page), else from the language. Or one's own
# list: name (said and shown on the TV), FM frequency (to ask for it:
# "Robot, radio 105.5"; only a name, the sound comes from the internet) and
# address of the stream, for example:
#   RADIO_STATIONS = [
#       {"name": "France Inter", "frequency": 87.8, "url": "https://icecast.radiofrance.fr/franceinter-midfi.mp3"},
#   ]
# Played on the USB speaker.
RADIO_STATIONS = None

# --- Resolution of the screen (display_mode.py) ---
# "1080p" = a TV giving 4K (3840 x 2160) is set to 1920 x 1080, up to 60 Hz:
# much lighter for the Raspberry, smoother video calls. Screens of 1920
# pixels or less are never changed. None = left as the TV wants it.
SCREEN_MODE = "1080p"

# --- Nightly restart of the Raspberry (self-repair, selfheal.py) ---
# Hour (0 to 23, local time) at which the Raspberry restarts every night,
# quietly (the TV is not turned on), never during a call. None = never.
NIGHTLY_REBOOT_HOUR = 4

# --- Ringtone (WAV, made from the .mp3 by install.sh) ---
# Played in a loop under the voice announcement, or alone if the TTS fails.
# Default: ringtone.mp3 of the project ("game-music1" by Nia Mi, CC0, see the
# README). Another ringtone: copy its .mp3 into ~/AppelerMamie, run install.sh
# again (it makes the .wav), then put the path of the .wav here.
RINGTONE_PATH = str(BASE_DIR / "ringtone.wav")

# --- Maximum time (in seconds) the call window stays open before the
#     call is considered "not answered" ---
CALL_DURATION = 30

# --- Maximum number of call audio files kept in cache (one per name and
#     language). Beyond that, the least recently used are deleted ---
MAX_CACHED_CALLS = 30

# --- Maximum length of the spoken caller name (same limit as the server) ---
MAX_CALLER_NAME_LENGTH = 30

# --- Relative volumes used when mixing the TTS voice with the ringtone ---
# (settings page of the TV: "music" 1 to 10 = RINGTONE_VOLUME 0.1 to 1.0,
# "voice" 1 to 13 = VOICE_VOLUME 0.15 to 1.95, 10 = 1.5)
VOICE_VOLUME = 1.5
RINGTONE_VOLUME = 0.2

# --- Device identity, filled at startup by identity.load_identity() ---
# NB: these two variables are "globals" shared between modules.
# They are stored here (config module) so they are reachable everywhere
# through `import config` without duplicating logic.
RASPBERRY_ID = None
DEVICE_SECRET = None


# --- Settings changed on the TV (settings page, settings_store.py) ---
# settings.json, written by the agent when "Apply" is confirmed on the TV,
# takes precedence over the values above for LANGUAGE, RINGTONE_VOLUME,
# VOICE_VOLUME and the place of the weather. install.sh writes them back here and removes it.
try:
    import settings_store as _settings_store
    _settings_store.apply(globals())
except Exception as _error:  # a broken file must never stop the Raspberry
    print(f"⚠️ settings.json not applied ({_error})")
